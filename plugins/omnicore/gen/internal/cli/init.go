package cli

import (
	"fmt"
	"io"
	"os"
	"path/filepath"
	"strings"

	"github.com/ClaudioSchirmer/omnicore-plugin/gen/internal/discover"
	"github.com/ClaudioSchirmer/omnicore-plugin/gen/internal/layout"
	"github.com/ClaudioSchirmer/omnicore-plugin/gen/internal/naming"
)

// Init writes a spec template that already knows the project.
//
// A blank template would make the author restate what the project already
// states — the dialects, whether there is a Mongo to project into, which value
// objects exist — and every restatement is a chance to disagree with reality.
// So the template arrives with those slots decided and the rest commented, and
// the comments say WHY a choice matters rather than what the key is called.
type InitOptions struct {
	Entity     string
	ProjectDir string
	Out        string
	Force      bool
}

func Init(w io.Writer, opt InitOptions) error {
	if opt.Entity == "" {
		return fmt.Errorf("init needs the entity name, e.g. omnicore-gen init Student")
	}
	if !isPascal(opt.Entity) {
		return fmt.Errorf("%q is not a usable entity name — use PascalCase with no "+
			"underscores, e.g. Student", opt.Entity)
	}

	proj, err := discover.Find(opt.ProjectDir)
	if err != nil {
		return err
	}

	path := opt.Out
	if path == "" {
		path = layout.SpecIn(proj.Root, naming.Snake(opt.Entity))
	}
	if _, err := os.Stat(path); err == nil && !opt.Force {
		return fmt.Errorf("%s already exists — edit it, or pass -force to start over "+
			"(which discards what is there)", path)
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(path, []byte(renderTemplate(opt.Entity, proj)), 0o644); err != nil {
		return err
	}

	fmt.Fprintf(w, "Wrote %s\n\n", path)
	fmt.Fprintf(w, "Filled in from the project: dialect(s) %s, read backing %s.\n",
		strings.Join(proj.Dialects, ", "), backingFor(proj))
	if len(proj.ExistingVOs) > 0 {
		fmt.Fprintf(w, "Value objects already here, reusable by name: %s.\n",
			strings.Join(proj.ExistingVOs, ", "))
	}
	fmt.Fprintf(w, "\nThe template does not validate as written — the field list is a "+
		"placeholder.\nFill it in, then run:\n\n  omnicore-gen check -spec %s\n", path)
	return nil
}

func isPascal(s string) bool {
	if s == "" || s[0] < 'A' || s[0] > 'Z' {
		return false
	}
	for _, r := range s {
		if !(r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9') {
			return false
		}
	}
	return true
}

// backingFor picks the read side the project can actually serve.
//
// Without a Mongo there is nothing to project into, so a Mongo-backed view
// would abort the boot — the template must not hand someone a spec their own
// service refuses to start with.
func backingFor(p *discover.Project) string {
	if p.HasMongo {
		return "mongo"
	}
	return "relational"
}

func renderTemplate(entity string, p *discover.Project) string {
	var b strings.Builder
	// The table is suggested from the entity in singular — a case change of a
	// name the author already gave. The PLURAL is left blank: inventing it is
	// exactly what this generator does not do, and a template that quietly
	// guessed it would put the guess in a route path.
	table := naming.Snake(entity)
	resource := strings.ToLower(entity)
	backing := backingFor(p)

	fmt.Fprintf(&b, "# %s — generated by omnicore-gen init.\n#\n", entity)
	b.WriteString("# The slots this file could answer from the project are already answered;\n")
	b.WriteString("# the rest is yours. FILL this template — do not replace it with a file\n")
	b.WriteString("# written from scratch, which is how the wrong dialect and an unservable\n")
	b.WriteString("# read backing get in.\n#\n")
	b.WriteString("# Before filling it in, run\n")
	b.WriteString("#   omnicore-gen explain keys                 — every key there is\n")
	b.WriteString("#   omnicore-gen explain example [sharedbase] — a whole spec that validates\n")
	b.WriteString("# `explain keys` is the one that saves time: most of what looks like \"the\n")
	b.WriteString("# generator cannot express this\" is a key whose name is not guessable.\n#\n")
	fmt.Fprintf(&b, "# Discovered here: dialect(s) %s · read backing %s.\n",
		strings.Join(p.Dialects, ", "), backing)
	if len(p.ExistingVOs) > 0 {
		fmt.Fprintf(&b, "# Value objects this project already has: %s\n",
			strings.Join(p.ExistingVOs, ", "))
		b.WriteString("# Reuse one with  vo: {kind: reuse, ref: <Name>}  rather than declaring\n")
		b.WriteString("# a second copy — two copies of a rule can disagree.\n")
	}
	b.WriteString("\nspecVersion: 1\n")
	fmt.Fprintf(&b, "entity: %s\n", entity)
	b.WriteString("# REQUIRED. It reaches the route path, the feature name and the listing\n")
	b.WriteString("# types. No rule can spell it — an English heuristic writes neither\n")
	b.WriteString("# \"Matriculas\" nor \"Analyses\" — so you declare it.\n")
	b.WriteString("plural:\n")
	b.WriteString("language: pt-BR\n\n")

	b.WriteString("storage:\n")
	b.WriteString("  # flat = its own table. sharedbase-role = a ROLE over an identity that\n")
	b.WriteString("  # other roles may share (a person who is a student today and staff later).\n")
	b.WriteString("  # Starting flat and extracting a shared identity afterwards is a real\n")
	b.WriteString("  # migration, so it is worth a minute now.\n")
	b.WriteString("  kind: flat\n")
	b.WriteString("  # Suggested from the entity name, in singular. Change it to whatever the\n")
	b.WriteString("  # table is really called.\n")
	fmt.Fprintf(&b, "  table: %s\n", table)
	fmt.Fprintf(&b, "  description: TODO — one line; it becomes the table comment.\n")
	b.WriteString("  managed:\n")
	b.WriteString("    # revision is required. The archive column is what makes archive/unarchive\n")
	b.WriteString("    # possible at all — drop it and those verbs are refused.\n")
	b.WriteString("    revision: revision\n")
	b.WriteString("    createdAt: created_at\n")
	b.WriteString("    updatedAt: updated_at\n")
	b.WriteString("    archivedAt: deleted_at\n\n")

	b.WriteString("fields:\n")
	b.WriteString("  # A string needs a length: a zero-length column is rejected outright by\n")
	b.WriteString("  # postgres, sqlserver and oracle. Money is int64 in minor units, never a\n")
	b.WriteString("  # float. A value whose set is fixed is an enum value object, not a string.\n")
	b.WriteString("  - name: Nome\n")
	b.WriteString("    type: string\n")
	b.WriteString("    column: nome\n")
	b.WriteString("    length: 120\n")
	b.WriteString("    livesOn: root\n")
	b.WriteString("    example: TODO\n")
	b.WriteString("    description: TODO — becomes the column comment and the field's label.\n\n")

	b.WriteString("modes: [display, insert, update, archive, unarchive]\n\n")
	b.WriteString("update:\n")
	b.WriteString("  # patch is the common case. A sibling facet forces put or both, because\n")
	b.WriteString("  # PATCH cannot say \"set this to null\" and the facet could never be cleared.\n")
	b.WriteString("  shape: patch\n\n")
	b.WriteString("delete:\n")
	b.WriteString("  # soft = archive, reversible. hard = DELETE, a permanent purge — and the\n")
	b.WriteString("  # HTTP verb has to tell the truth about which one it is.\n")
	b.WriteString("  root: soft\n\n")

	b.WriteString("rules:\n")
	b.WriteString("  list:\n")
	b.WriteString("    - id: nome-obrigatorio\n")
	b.WriteString("      kind: required\n")
	b.WriteString("      scope: [insertOrUpdate]\n")
	b.WriteString("      fields: [Nome]\n")
	b.WriteString("      notification: RequiredFieldNotification\n")
	b.WriteString("  # Anything the DSL cannot express goes here as a NAMED item. The text is\n")
	b.WriteString("  # what the report tells the implementer to write, and it lands as a stub\n")
	b.WriteString("  # in a file regeneration never touches.\n")
	b.WriteString("  # manual:\n")
	b.WriteString("  #   - id: alguma-regra\n")
	b.WriteString("  #     description: >-\n")
	b.WriteString("  #       O que precisa ser garantido, em uma frase que alguém consiga implementar.\n")
	b.WriteString("  #     scope: [insert]\n\n")

	b.WriteString("read:\n")
	fmt.Fprintf(&b, "  backing: %s\n", backing)
	if backing == "relational" {
		b.WriteString("  # relational: reads come straight from the tables, so a write is visible\n")
		b.WriteString("  # to the very next read. This project has no mongo block, so it is the\n")
		b.WriteString("  # only backing that can serve here.\n")
	} else {
		b.WriteString("  # mongo: reads come from a projection updated shortly after the write.\n")
		b.WriteString("  # Bump view.version whenever the projected shape changes, or the service\n")
		b.WriteString("  # refuses to boot rather than serve a stale projection.\n")
	}
	b.WriteString("  view:\n")
	fmt.Fprintf(&b, "    name: %s\n", table)
	b.WriteString("    version: 1\n")
	b.WriteString("    maxLimit: 100\n")
	if backing == "mongo" {
		b.WriteString("  # indexes:\n")
		b.WriteString("  #   - {fields: [Nome], unique: true}\n")
		b.WriteString("  #   - {fields: [Nome], text: true}   # required to serve ?search=\n")
	}
	b.WriteString("  byId: true\n")
	b.WriteString("  byParams:\n")
	b.WriteString("    filters:\n")
	b.WriteString("      - {field: Nome, ops: [eq, contains, icontains]}\n")
	b.WriteString("    # A control is served ONLY if declared. Undeclared, its mere presence on\n")
	b.WriteString("    # the wire is answered with a typed 400 — that is a contract, not an omission.\n")
	b.WriteString("    controls:\n")
	b.WriteString("      pagination: true\n")
	b.WriteString("      orderBy: true\n")
	b.WriteString("      includeArchived: true\n\n")

	b.WriteString("# children:\n")
	b.WriteString("#   - name: Item\n")
	b.WriteString("#     # REQUIRED, and it is a PERSISTED key: the document segment, the read\n")
	b.WriteString("#     # DTO field and the notification path, all from this one name.\n")
	b.WriteString("#     plural: Itens\n")
	b.WriteString("#     table: TODO_itens\n")
	b.WriteString("#     # REQUIRED. A column name outlives the decision that made it.\n")
	b.WriteString("#     parentColumn: TODO_id\n")
	b.WriteString("#     ownedBy: root\n")
	b.WriteString("#     # atomic-replace: the root's update swaps the WHOLE collection.\n")
	b.WriteString("#     # per-child: POST/PUT/DELETE per entry, a duplicate answer on add\n")
	b.WriteString("#     # (declare duplicateNotification) and a 404 for an entry that is\n")
	b.WriteString("#     # not there. Adding one entry should not mean resending the rest.\n")
	b.WriteString("#     editStrategy: atomic-replace\n")
	b.WriteString("#     businessIdentity: [TODO]\n")
	b.WriteString("#     fields: []\n\n")
	b.WriteString("surfaces:\n")
	b.WriteString("  rest: true\n")
	b.WriteString("  # graphql: {enabled: true, connection: true, mutations: [insert, update, archive, unarchive]}\n")
	b.WriteString("  # exports: {csv: {delimiter: \";\"}, xlsx: {sheet: TODO}}\n\n")

	b.WriteString("authz:\n")
	fmt.Fprintf(&b, "  resource: %s\n", resource)
	b.WriteString("  # anyone-with-permission means every holder of the permission sees every\n")
	b.WriteString("  # row. owner-only and tenant narrow it — and that is a different question\n")
	b.WriteString("  # from the permission itself, which is why both are asked.\n")
	b.WriteString("  dataAccess: anyone-with-permission\n")
	b.WriteString("  permissions:\n")
	fmt.Fprintf(&b, "    insert: %s:escrever\n", resource)
	fmt.Fprintf(&b, "    patch: %s:escrever\n", resource)
	fmt.Fprintf(&b, "    archive: %s:arquivar\n", resource)
	fmt.Fprintf(&b, "    unarchive: %s:arquivar\n", resource)
	fmt.Fprintf(&b, "    read: %s:ler\n", resource)
	return b.String()
}
