// TestEverySpecStructIsRegistered keeps the key-suggestion index honest. A new
// struct in the language that nobody registers would silently lose its
// "did you mean" hints, and the loss would be invisible.
func TestEverySpecStructIsRegistered(t *testing.T) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, "spec.go", nil, 0)
	if err != nil {
		t.Fatalf("parsing spec.go: %v", err)
	}
	ast.Inspect(f, func(n ast.Node) bool {
		ts, ok := n.(*ast.TypeSpec)
		if !ok {
			return true
		}
		if _, isStruct := ts.Type.(*ast.StructType); !isStruct {
			return true
		}
		if _, registered := specTypes[ts.Name.Name]; !registered {
			t.Errorf("type %s is part of the spec language but is not in specTypes; "+
				"unknown-key suggestions inside it will silently do nothing", ts.Name.Name)
		}
		return true
	})
}

// TestEveryCapabilityIsAccountedFor is the INV-1 gate at the capability level:
// a capability must be either implemented or refused with a named phase. One
// that is neither would be accepted by the loader and generated by nobody.
func TestEveryCapabilityIsAccountedFor(t *testing.T) {
	for _, c := range AllCapabilities() {
		done, listed := implemented[c]
		if !listed {
			t.Errorf("capability %q has no entry in `implemented` — it would fall through the "+
				"coverage gate and be silently ignored", c)
			continue
		}
		if !done {
			if _, ok := phaseOf[c]; !ok {
				t.Errorf("capability %q is not implemented and names no phase — a refusal must "+
					"tell the author when to expect it", c)
			}
		}
	}
	for c := range implemented {
		if !containsCap(AllCapabilities(), c) {
			t.Errorf("capability %q is in `implemented` but missing from AllCapabilities()", c)
		}
	}
}

// TestRefusedCapabilitiesAreActuallyRefused proves the gate bites: for every
// capability this build does not implement, a spec using it must be refused.
// Without this, flipping a flag off would silently do nothing.
func TestRefusedCapabilitiesAreActuallyRefused(t *testing.T) {
	cases := map[Capability]func(*Spec){
		CapSharedBase: func(s *Spec) {
			s.Storage.Kind = "sharedbase-role"
		},
		CapValueObjects: func(s *Spec) {
			s.ValueObjects = []ValueObject{{Name: "Email", Kind: "raw", Backing: "string"}}
		},
		CapChildren: func(s *Spec) {
			s.Children = []Child{{Name: "Grade", Table: "student_grades"}}
		},
		CapSiblings: func(s *Spec) {
			s.Siblings = []Sibling{{Name: "Facet", Table: "student_facets"}}
		},
		CapService: func(s *Spec) {
			s.Service = &Service{Required: true}
		},
		CapMongoView: func(s *Spec) {
			s.Read.Backing = "mongo"
		},
		CapGraphQL: func(s *Spec) {
			s.Surfaces.GraphQL = &GraphQL{Enabled: true}
		},
		CapExports: func(s *Spec) {
			s.Surfaces.Exports = &Exports{CSV: &CSVExport{Delimiter: ","}}
		},
		CapFieldRestrict: func(s *Spec) {
			s.Read.FieldRestrict = []FieldRestrict{{Field: "Name", Permission: "x:y"}}
		},
		CapOwnerAccess: func(s *Spec) {
			s.Authz.DataAccess = "owner-only"
		},
		CapTenantAccess: func(s *Spec) {
			s.Authz.DataAccess = "tenant"
		},
	}
	for cap, mutate := range cases {
		if Implemented(cap) {
			continue // implemented now; the refusal is correctly gone
		}
		s := minimalSpec()
		mutate(s)
		ps := CheckCoverage(s)
		if !ps.HasBlockers() {
			t.Errorf("capability %q is not implemented, but a spec using it was NOT refused", cap)
		}
	}
}

func containsCap(all []Capability, c Capability) bool {
	for _, a := range all {
		if a == c {
			return true
		}
	}
	return false
}

// minimalSpec is the smallest spec this build generates: a flat entity with one
// field, insert-only, REST.
func minimalSpec() *Spec {
	return &Spec{
		SpecVersion: 1,
		Entity:      "Student",
		Language:    "pt-BR",
		Storage: Storage{
			Kind:        "flat",
			Table:       "students",
			Description: "Alunos matriculados.",
			Managed:     Managed{Revision: "revision", CreatedAt: "created_at", UpdatedAt: "updated_at"},
		},
		Fields: []Field{{
			Name: "Name", Type: "string", Column: "name", Length: 120,
			LivesOn: "root", Example: "Ana", Description: "Nome do aluno.",
		}},
		Modes:    []string{"display", "insert"},
		Read:     Read{Backing: "relational", View: View{Name: "students", Version: 1}, ByID: true},
		Surfaces: Surfaces{REST: true},
		Authz: Authz{
			Resource:    "student",
			DataAccess:  "anyone-with-permission",
			Permissions: map[string]string{"insert": "student:write", "read": "student:read"},
		},
	}
}

// TestMinimalSpecIsClean guards the fixture the other tests build on: if the
// baseline itself is invalid, every "X is refused" assertion above is vacuous.
func TestMinimalSpecIsClean(t *testing.T) {
	ps := Validate(minimalSpec(), Options{})
	if ps.HasBlockers() {
		t.Fatalf("the minimal spec should validate cleanly, got:\n%v", ps.Error())
	}
	if cov := CheckCoverage(minimalSpec()); cov.HasBlockers() {
		t.Fatalf("the minimal spec should be fully covered, got:\n%v", cov.Error())
	}
}

func TestUnknownKeyIsRefusedWithSuggestion(t *testing.T) {
	_, err := Parse([]byte("specVersion: 1\nentty: Student\n"), "x.yaml")
	if err == nil {
		t.Fatal("an unknown key must be an error")
	}
	if !strings.Contains(err.Error(), "entty") {
		t.Errorf("the error should name the offending key, got: %v", err)
	}
	if !strings.Contains(err.Error(), "entity") {
		t.Errorf("the error should suggest the near key, got: %v", err)
	}
}
